interface ProductSeed {
  slug: string;
  name: string;
  subtitle?: string;
  shortDescription: string;
  description: string;
  category: CategorySlug;
  collection: string;
  collectionName: string;
  price: number;
  compareAtPrice?: number;
  images: ProductImage[];
  metal: Metal;
  gemstone: Gemstone;
  gemstoneLabel?: string;
  carat?: string;
  materialWeight?: string;
  setting?: string;
  finish?: string;
  sizes?: string[];
  availableMetals?: Metal[];
  isNew?: boolean;
  isBestSeller?: boolean;
  isFeatured?: boolean;
  availability?: Availability;
  launchedAt: string;
  tags: string[];
  extraDetails?: ProductDetail[];
}

/** Builds a complete product, deriving subtitle and specification rows. */
function defineProduct(seed: ProductSeed, index: number): Product {
  const gemstoneLabel =
    seed.gemstoneLabel ?? (seed.gemstone === "None" ? undefined : `Natural ${seed.gemstone}`);

  const details: ProductDetail[] = [
    { label: "Material", value: seed.metal },
    ...(gemstoneLabel ? [{ label: "Gemstone", value: gemstoneLabel }] : []),
    ...(seed.carat ? [{ label: "Total Weight", value: seed.carat }] : []),
    ...(seed.materialWeight ? [{ label: "Metal Weight", value: seed.materialWeight }] : []),
    ...(seed.setting ? [{ label: "Setting", value: seed.setting }] : []),
    { label: "Finish", value: seed.finish ?? "High Polish" },
    ...(seed.extraDetails ?? []),
    { label: "Collection", value: seed.collectionName },
    { label: "Reference", value: `AUR-${String(1040 + index * 7).padStart(5, "0")}` },
  ];

  return {
    id: `p-${String(index + 1).padStart(3, "0")}`,
    slug: seed.slug,
    name: seed.name,
    subtitle: seed.subtitle ?? [seed.metal, gemstoneLabel].filter(Boolean).join(" · "),
    shortDescription: seed.shortDescription,
    description: seed.description,
    category: seed.category,
    collection: seed.collection,
    price: seed.price,
    compareAtPrice: seed.compareAtPrice,
    images: seed.images,
    metal: seed.metal,
    gemstone: seed.gemstone,
    carat: seed.carat,
    materialWeight: seed.materialWeight,
    sizes: seed.sizes,
    availableMetals: seed.availableMetals,
    isNew: seed.isNew,
    isBestSeller: seed.isBestSeller,
    isFeatured: seed.isFeatured,
    availability: seed.availability ?? "in-stock",
    launchedAt: seed.launchedAt,
    details,
    tags: seed.tags,
  };
}

